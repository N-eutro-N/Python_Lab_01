# Ключ шифра: (номер строки, срез) для каждого слова фразы
WORD_SLICES = (
    (0, slice(3, 4)),        # 4-я буква
    (1, slice(9, 13)),       # буквы 10-13
    (2, slice(5, 15, 2)),    # буквы 6-15 через одну
    (3, slice(12, 6, -1)),   # буквы 8-13 в обратном порядке
    (4, slice(20, 15, -1)),  # буквы 17-21 в обратном порядке
)


def decode_secret(lines, word_slices=WORD_SLICES):
    #Собирает фразу из срезов строк шифровки
    return ' '.join(lines[line][cut] for line, cut in word_slices)


